#!/usr/bin/env python3
"""Exhaustive order-36 experiment using GroupNames permutation generators.

All 14 isomorphism classes are reconstructed independently by permutation closure.
Order-6 subgroups are exhausted using the classification C6 and S3 only.
"""
from __future__ import annotations
import html
import json
import re
import time
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np
from scipy.optimize import milp, LinearConstraint, Bounds
from scipy.sparse import csc_matrix

ROOT = Path(__file__).resolve().parent
CACHE = ROOT / "groupnames_cache"
BASE = "https://people.maths.bris.ac.uk/~matyd/GroupNames/"


def fetch(path):
    CACHE.mkdir(exist_ok=True)
    target = CACHE / path.replace("/", "_")
    if not target.exists():
        with urllib.request.urlopen(BASE + path, timeout=30) as response:
            target.write_bytes(response.read())
    return target.read_text(encoding="utf-8")


def compose(p, q):
    return tuple(q[p[i]] for i in range(len(p)))


def power_order(p, identity):
    x = p
    for k in range(1, 1000):
        if x == identity:
            return k
        x = compose(x, p)
    raise ValueError("permutation order too large")


def closure(generators, identity):
    result = {identity}
    frontier = [identity]
    while frontier:
        x = frontier.pop()
        for g in generators:
            y = compose(x, g)
            if y not in result:
                result.add(y)
                frontier.append(y)
    return result


def parse_permutations(text, degree):
    identity = tuple(range(degree))
    generators = []
    # Each HTML line is one generator; disjoint cycles on that line are its product.
    for chunk in re.split(r"<br\s*/?>|\r?\n", text):
        p = list(identity)
        used = False
        for token in re.findall(r"\([^()]+\)", chunk):
            used = True
            entries = [int(x)-1 for x in re.findall(r"\d+", token)]
            for i, x in enumerate(entries):
                p[x] = entries[(i+1) % len(entries)]
        if used:
            generators.append(tuple(p))
    return generators


def reconstruct(path):
    page = fetch(path)
    gid = int(re.search(r"SmallGroup\(36,(\d+)\)", page).group(1))
    structure = html.unescape(re.search(r"<title>(.*?) - GroupNames</title>", page).group(1))
    match = re.search(r"<pre class='pre' id='textgn1'>(.*?)</pre>", page, re.S)
    if not match:
        raise ValueError(f"No permutation representation in {path}")
    perm_text = html.unescape(match.group(1))
    degree = max(map(int, re.findall(r"\d+", perm_text)))
    identity = tuple(range(degree))
    generators = parse_permutations(perm_text, degree)
    elements = closure(generators, identity)
    assert len(elements) == 36, (path, len(elements))
    assert closure(generators + [compose(g, g) for g in generators], identity) == elements
    ordered = [identity] + sorted(elements - {identity})
    return {"id": gid, "structure": structure, "path": path,
            "degree": degree, "generators": generators,
            "elements": ordered, "identity": identity}


def order6_subgroups(group):
    elements = group["elements"]
    identity = group["identity"]
    orders = {x: power_order(x, identity) for x in elements}
    subs = set()
    # Every cyclic C6 occurs as <x> with x of order 6.
    for x in elements:
        if orders[x] == 6:
            H = closure([x], identity)
            assert len(H) == 6
            subs.add(frozenset(H))
    # Every noncyclic group of order 6 is S3, generated by an involution
    # and an element of order 3. Taking every pair also rediscovers C6.
    involutions = [x for x in elements if orders[x] == 2]
    cubes = [x for x in elements if orders[x] == 3]
    for a in involutions:
        for b in cubes:
            H = closure([a, b], identity)
            if len(H) == 6:
                subs.add(frozenset(H))
    # Independent subgroup axioms check.
    for H in subs:
        assert identity in H and len(H) == 6
        for a in H:
            assert power_order(a, identity) in (1, 2, 3, 6)
            for b in H:
                assert compose(a, b) in H
    return subs


def masks_for(group, subs):
    pos = {x: i for i, x in enumerate(group["elements"])}
    masks = []
    for H in subs:
        mask = sum(1 << pos[x] for x in H)
        assert mask.bit_count() == 6 and mask & 1
        masks.append(mask)
    return sorted(masks)


def cover_matrix(masks):
    full = (1 << 36) - 1
    nonidentity = full ^ 1
    union = 0
    for m in masks:
        union |= m
    if union != full:
        return None, full, full ^ union
    rows, cols = [], []
    for j, mask in enumerate(masks):
        mm = mask & nonidentity
        while mm:
            bit = mm & -mm
            rows.append(bit.bit_length()-2)  # bits 1..35 -> rows 0..34
            cols.append(j)
            mm ^= bit
    A = csc_matrix((np.ones(len(rows)), (rows, cols)), shape=(35, len(masks)))
    return A, full, 0


def solve_group(group):
    subs = order6_subgroups(group)
    masks = masks_for(group, subs)
    A, full, uncovered = cover_matrix(masks)
    rec = {"smallgroup_id": [36, group["id"]], "structure": group["structure"],
           "source": BASE + group["path"], "permutation_degree": group["degree"],
           "group_order_verified": len(group["elements"]),
           "subgroup_count": len(masks), "lower_bound": 7}
    if not masks or uncovered:
        rec.update(m=None, status="no_cover", uncovered_elements=(uncovered.bit_count() if uncovered else 36))
        return rec
    h = len(masks)
    constraints = LinearConstraint(A, np.ones(35), np.full(35, np.inf))
    result = milp(np.ones(h), integrality=np.ones(h), bounds=Bounds(0, 1),
                  constraints=constraints,
                  options={"time_limit": 60, "mip_rel_gap": 0.0})
    rec["solver_status"] = int(result.status)
    rec["solver_message"] = result.message
    dual = getattr(result, "mip_dual_bound", None)
    if dual is not None and np.isfinite(dual):
        rec["lower_bound"] = max(7, int(np.ceil(dual-1e-7)))
    if result.x is not None:
        chosen = [m for m, x in zip(masks, result.x) if x > 0.5]
        union = 0
        for m in chosen:
            union |= m
        assert union == full
        rec.update(m=len(chosen), witness_masks=[str(m) for m in chosen],
                   covered_elements=union.bit_count(), union_equals_group=True,
                   status="optimal" if result.status == 0 else "timeout_upper_bound")
    else:
        rec.update(m=None, status="no_cover" if result.status == 2 else "timeout_no_incumbent")
    return rec


def main():
    index = fetch("index.html")
    section = index[index.index("id='order36'"):index.index("id='order37'")]
    paths = list(dict.fromkeys(re.findall(r'<tr><td id="[^"]+"><a href="(1/[^"]+\.html)"', section)))
    assert len(paths) == 14, paths
    with ThreadPoolExecutor(max_workers=14) as pool:
        list(pool.map(fetch, paths))
    groups = [reconstruct(path) for path in paths]
    assert sorted(g["id"] for g in groups) == list(range(1, 15))
    results = []
    for g in sorted(groups, key=lambda x: x["id"]):
        t0 = time.time()
        rec = solve_group(g)
        rec["elapsed_seconds"] = round(time.time()-t0, 3)
        results.append(rec)
        print(json.dumps(rec, ensure_ascii=False), flush=True)
    finite = [r["m"] for r in results if r["m"] is not None]
    best = min(finite)
    exact = all(r["m"] is None or (r["status"] == "optimal" and r["m"] == r["lower_bound"])
                for r in results)
    summary = {"n": 6, "groups_enumerated": len(results), "minimum_m": best,
               "exact": exact,
               "attaining_groups": [[r["smallgroup_id"], r["structure"], r["subgroup_count"]]
                                    for r in results if r["m"] == best]}
    output = {"method": "GroupNames permutation generators + independent closure + exhaustive C6/S3 generation + SciPy HiGHS",
              "summary": summary, "groups": results}
    (ROOT / "order36_results.json").write_text(json.dumps(output, indent=2, ensure_ascii=False), encoding="utf-8")
    print("SUMMARY " + json.dumps(summary, ensure_ascii=False))


if __name__ == "__main__":
    main()

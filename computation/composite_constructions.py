#!/usr/bin/env python3
"""Exact covers for coverable order-100 types and constructions at order 144."""
from __future__ import annotations
import itertools
import json
import math
import time
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from scipy.optimize import milp, LinearConstraint, Bounds
from scipy.sparse import csc_matrix
from sympy.combinatorics.named_groups import AlternatingGroup

ROOT = Path(__file__).resolve().parent


@dataclass
class AbstractGroup:
    name: str
    n: int
    identity: object
    mul: object
    elements: list

    def closure(self, generators):
        result = {self.identity}
        frontier = [self.identity]
        while frontier:
            x = frontier.pop()
            for g in generators:
                y = self.mul(x, g)
                if y not in result:
                    result.add(y)
                    frontier.append(y)
        return result

    def order(self, x):
        y = x
        for k in range(1, len(self.elements)+1):
            if y == self.identity:
                return k
            y = self.mul(y, x)
        raise AssertionError("bad multiplication")


def semidirect100(name, action):
    # N=F5^2, H=C2^2; action(h) is one of the three C2-actions classified in results.md.
    def phi(h, v):
        x, y = v
        u, w = h
        if action == "global" and u:
            x, y = -x, -y
        elif action == "reflection" and u:
            x = -x
        elif action == "faithful":
            if u:
                x = -x
            if w:
                y = -y
        return x % 5, y % 5
    def mul(a, b):
        (v, h), (w, j) = a, b
        z = phi(h, w)
        return ((v[0]+z[0]) % 5, (v[1]+z[1]) % 5), ((h[0]+j[0]) % 2, (h[1]+j[1]) % 2)
    identity = ((0, 0), (0, 0))
    elements = [((x, y), (u, w)) for x in range(5) for y in range(5)
                for u in range(2) for w in range(2)]
    elements.remove(identity)
    return AbstractGroup(name, 10, identity, mul, [identity] + elements)


def abelian_group(name, n, moduli):
    identity = (0,) * len(moduli)
    def mul(a, b):
        return tuple((x+y) % m for x, y, m in zip(a, b, moduli))
    elements = [identity] + [x for x in itertools.product(*(range(m) for m in moduli)) if x != identity]
    return AbstractGroup(name, n, identity, mul, elements)


def a4_squared():
    perms = [tuple(p.array_form) for p in AlternatingGroup(4).elements]
    identity_p = tuple(range(4))
    def comp(p, q):
        return tuple(q[p[i]] for i in range(4))
    def mul(a, b):
        return comp(a[0], b[0]), comp(a[1], b[1])
    identity = (identity_p, identity_p)
    elements = [identity] + [x for x in itertools.product(perms, repeat=2) if x != identity]
    return AbstractGroup("A4^2", 12, identity, mul, elements)


def subgroups_by_pairs(group):
    target = group.n
    result = set()
    elements = group.elements
    # Every group of order 10 or 12 is generated by at most two elements.
    for i, a in enumerate(elements):
        for b in elements[i:]:
            H = group.closure([a, b])
            if len(H) == target:
                result.add(frozenset(H))
    for H in result:
        assert group.identity in H
        for a in H:
            for b in H:
                assert group.mul(a, b) in H
    return result


def masks_for(group, subgroups):
    pos = {x: i for i, x in enumerate(group.elements)}
    masks = sorted(sum(1 << pos[x] for x in H) for H in subgroups)
    assert all(m.bit_count() == group.n and m & 1 for m in masks)
    return masks


def greedy(group, masks):
    full = (1 << len(group.elements))-1
    covered = 1
    chosen = []
    remaining = set(masks)
    while covered != full:
        best = max(remaining, key=lambda m: (m & ~covered).bit_count())
        if not best & ~covered:
            return None
        chosen.append(best)
        covered |= best
        remaining.remove(best)
    return chosen


def solve(group, time_limit):
    t0 = time.time()
    assert len(group.elements) == group.n**2
    # Multiplication and inverses sanity checks on all elements.
    for x in group.elements:
        assert group.mul(x, group.identity) == x
        y = x
        while y != group.identity:
            y = group.mul(y, x)
    subgroups = subgroups_by_pairs(group)
    masks = masks_for(group, subgroups)
    full = (1 << len(group.elements))-1
    union = 0
    for m in masks:
        union |= m
    rec = {"structure": group.name, "n": group.n, "order": len(group.elements),
           "subgroup_count": len(masks), "lower_bound": group.n+1}
    if union != full:
        rec.update(status="no_cover", m=None,
                   uncovered_element_count=(full ^ union).bit_count())
        return rec
    h = len(masks)
    rows, cols = [], []
    for j, mask in enumerate(masks):
        mm = mask ^ 1
        while mm:
            bit = mm & -mm
            rows.append(bit.bit_length()-2)
            cols.append(j)
            mm ^= bit
    A = csc_matrix((np.ones(len(rows)), (rows, cols)), shape=(len(group.elements)-1, h))
    constraints = LinearConstraint(A, np.ones(len(group.elements)-1),
                                   np.full(len(group.elements)-1, np.inf))
    result = milp(np.ones(h), integrality=np.ones(h), bounds=Bounds(0, 1),
                  constraints=constraints,
                  options={"time_limit": time_limit, "mip_rel_gap": 0.0})
    rec["solver_status"] = int(result.status)
    rec["solver_message"] = result.message
    dual = getattr(result, "mip_dual_bound", None)
    if dual is not None and np.isfinite(dual):
        rec["lower_bound"] = max(group.n+1, int(math.ceil(dual-1e-7)))
    chosen = None
    if result.x is not None:
        chosen = [m for m, x in zip(masks, result.x) if x > 0.5]
        rec["status"] = "optimal" if result.status == 0 else "timeout_upper_bound"
    else:
        chosen = greedy(group, masks)
        rec["status"] = "greedy_upper_bound" if chosen else "timeout_no_incumbent"
    if chosen:
        covered = 0
        for m in chosen:
            covered |= m
        assert covered == full
        rec.update(m=len(chosen), witness_masks=[str(m) for m in chosen],
                   covered_elements=covered.bit_count(), union_equals_group=True)
    else:
        rec["m"] = None
    rec["elapsed_seconds"] = round(time.time()-t0, 3)
    return rec


def main():
    groups10 = [
        semidirect100("C2 x ((C5^2) : C2), global inversion", "global"),
        semidirect100("C2 x C5 x D5, reflection action", "reflection"),
        semidirect100("D5^2, faithful Klein action", "faithful"),
        abelian_group("C10^2", 10, [10, 10]),
    ]
    groups12 = [
        a4_squared(),
        abelian_group("C12^2", 12, [12, 12]),
        abelian_group("C6^2 x C4", 12, [6, 6, 4]),
        abelian_group("C6^2 x C2^2", 12, [6, 6, 2, 2]),
    ]
    results10, results12 = [], []
    for group in groups10:
        rec = solve(group, 120)
        results10.append(rec)
        print("n=10 " + json.dumps(rec, ensure_ascii=False), flush=True)
    finite = [r["m"] for r in results10 if r["m"] is not None]
    summary10 = {"n": 10, "minimum_m": min(finite) if finite else None,
                 "exact": bool(finite) and all(r["status"] == "optimal" and r["lower_bound"] == r["m"]
                                               for r in results10),
                 "scope": "All four coverable action types (trivial, global inversion, reflection, faithful Klein); every other order-100 group has an element of order 4 or 25.",
                 "attaining_groups": [[r["structure"], r["subgroup_count"]] for r in results10
                                      if r["m"] == min(finite)]}
    for group in groups12:
        rec = solve(group, 120)
        results12.append(rec)
        print("n=12 " + json.dumps(rec, ensure_ascii=False), flush=True)
    finite12 = [r["m"] for r in results12 if r["m"] is not None]
    summary12 = {"n": 12, "construction_upper_bound": min(finite12) if finite12 else None,
                 "universal_lower_bound": 13, "exact_global": 13 in finite12,
                 "scope": "Constructions only; not an enumeration of all 197 groups of order 144.",
                 "attaining_constructions": [[r["structure"], r["subgroup_count"], r["status"]]
                                             for r in results12 if r["m"] == min(finite12)]}
    output = {"order100": {"summary": summary10, "groups": results10},
              "order144": {"summary": summary12, "groups": results12}}
    (ROOT / "composite_results.json").write_text(json.dumps(output, indent=2, ensure_ascii=False), encoding="utf-8")
    print("SUMMARY10 " + json.dumps(summary10, ensure_ascii=False))
    print("SUMMARY12 " + json.dumps(summary12, ensure_ascii=False))


if __name__ == "__main__":
    main()
